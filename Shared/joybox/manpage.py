# Render a tool's man page
def render_page(tool_name, spec, descriptions = None):
    descriptions = descriptions or {}
    lines = [
        GENERATED_NOTICE % tool_name,
        "",
        "# %s" % tool_name,
        "",
        "[← Command index](README.md)",
        "",
        spec["description"].strip(),
        "",
        "## Synopsis",
        "",
        "```",
        format_synopsis(tool_name, spec),
        "```",
        "",
    ]
    if spec.get("details"):
        lines += ["## Description", "", spec["details"].strip(), ""]
    lines += ["## Options", ""]
    for group in spec["groups"]:
        lines += [
            "### %s" % (group["title"] or DEFAULT_GROUP_TITLE),
            "",
            "| Option | Description |",
            "|--------|-------------|",
        ]
        for option in group["options"]:
            lines.append("| %s | %s |" % (format_option_cell(option), format_description_cell(option)))
        lines.append("")
    if spec.get("examples"):
        lines += ["## Examples", ""]
        for title, command in spec["examples"]:
            lines += ["### %s" % title, "", "```bash", command, "```", ""]
    if spec.get("notes"):
        lines += ["## Notes", ""]
        lines += ["- %s" % note for note in spec["notes"]]
        lines.append("")
    if spec.get("see_also"):
        lines += ["## See also", ""]
        for other in spec["see_also"]:
            summary = descriptions.get(other)
            lines.append("- [%s](%s.md)%s" % (other, other, " — %s" % summary if summary else ""))
        lines.append("")
    return "\n".join(lines)

# Render the index of every tool, grouped by section
def render_index(specs):
    sections = {}
    for tool_name, spec in specs.items():
        sections.setdefault(spec.get("section") or DEFAULT_SECTION, []).append(tool_name)
    lines = [
        "<!-- Generated by build_man_pages. Edit the scripts' help text, not this file. -->",
        "",
        "# Command Reference",
        "",
        "[← Docs index](../../README.md)",
        "",
        "One page per command in `Scripts/bin`, generated from its `--help`. Every page is also",
        "available in the terminal as `<command> -h`.",
        "",
    ]
    for section in sorted(sections, key = lambda name: (name == DEFAULT_SECTION, name)):
        lines += ["## %s" % section, "", "| Command | Description |", "|---------|-------------|"]
        for tool_name in sorted(sections[section]):
            summary = specs[tool_name]["description"].strip().replace("|", "\\|")
            lines.append("| [%s](%s.md) | %s |" % (tool_name, tool_name, summary))
        lines.append("")
    return "\n".join(lines)

# Render every page, keyed by file name
def render_all(specs):
    descriptions = {name: spec["description"].strip().rstrip(".") for name, spec in specs.items()}
    pages = {"README.md": render_index(specs)}
    for tool_name, spec in specs.items():
        pages["%s.md" % tool_name] = render_page(tool_name, spec, descriptions)
    return pages

