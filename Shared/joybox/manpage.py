# Imports
import os
import os.path
import sys
import json
import subprocess
import tempfile
import textwrap
import tomllib

# Local imports
import joybox.default_settings as default_settings

# Header on every generated page
GENERATED_NOTICE = "<!-- Generated by build_man_pages from %s. Edit its help text, not this file. -->"

# The package every command lives in
COMMAND_PACKAGE = "joybox.cli"

# Title of the ungrouped options
DEFAULT_GROUP_TITLE = "General"

# Section for a tool that does not name one
DEFAULT_SECTION = "Other"

# Column prose is wrapped at, matching the repo's markdownlint line length
PAGE_WIDTH = 100

# The only environment a described script sees. Defaults can be read from the
# environment, and a token set in the shell must not end up on a page.
PASSED_ENVIRONMENT = ["PATH", "LANG", "LC_ALL", "SYSTEMROOT", "TEMP", "TMP"]

# Builds a command's parser and writes its description. The command module is
# imported, never run, and nothing is parsed.
PROBE_SOURCE = """
import importlib, json, sys
module_name, output_path = sys.argv[1], sys.argv[2]
parser = importlib.import_module(module_name).build_parser()
with open(output_path, "w") as output_file:
    json.dump(parser.describe(), output_file)
"""

# Get the commands a pyproject.toml declares, as (command, module) pairs
def find_commands(pyproject_path):
    with open(pyproject_path, "rb") as pyproject_file:
        scripts = tomllib.load(pyproject_file).get("project", {}).get("scripts", {})
    found = []
    for command, target in sorted(scripts.items()):
        module_name = target.split(":", 1)[0]
        if module_name.startswith(COMMAND_PACKAGE + "."):
            found.append((command, module_name))
    return found

# Get the source file a command module was generated from, relative to the repo
def get_module_source(module_name):
    return "Shared/%s.py" % module_name.replace(".", "/")

# Describe a command's parser, run against a home directory holding only the
# default JoyBox.ini so nothing from the local one leaks into the documentation
def describe_command(module_name, python_path, timeout = 60):
    with tempfile.TemporaryDirectory() as home_dir:
        default_settings.create_default_config_file(os.path.join(home_dir, "JoyBox.ini"))
        output_path = os.path.join(home_dir, "parser.json")
        env = {name: os.environ[name] for name in PASSED_ENVIRONMENT if name in os.environ}
        env["HOME"] = home_dir
        env["USERPROFILE"] = home_dir
        env["PYTHONPATH"] = os.pathsep.join(python_path)
        result = subprocess.run(
            [sys.executable, "-c", PROBE_SOURCE, module_name, output_path],
            check = False,
            capture_output = True,
            text = True,
            timeout = timeout,
            cwd = home_dir,
            env = env)
        if not os.path.exists(output_path):
            raise RuntimeError("Unable to describe %s: %s" % (module_name, result.stderr.strip()[-2000:]))
        with open(output_path, "r") as output_file:
            spec = json.load(output_file)
    spec = replace_home_in_defaults(spec, home_dir)
    spec["module"] = module_name
    return spec

# Swap the throwaway home directory for ~ in any default derived from it
def replace_home_in_defaults(spec, home_dir):
    def replace(value):
        if isinstance(value, str):
            return value.replace(home_dir, "~")
        if isinstance(value, list):
            return [replace(item) for item in value]
        return value
    for group in spec["groups"]:
        for option in group["options"]:
            option["default"] = replace(option["default"])
    return spec

