# Imports
import os, os.path
import sys
import json
import subprocess
import tempfile

# Local imports
import joybox.default_settings as default_settings

# Header on every generated page
GENERATED_NOTICE = "<!-- Generated by build_man_pages from Scripts/bin/%s.py. Edit the script's help text, not this file. -->"

# Title of the ungrouped options
DEFAULT_GROUP_TITLE = "General"

# Section for a tool that does not name one
DEFAULT_SECTION = "Other"

# The only environment a described script sees. Defaults can be read from the
# environment, and a token set in the shell must not end up on a page.
PASSED_ENVIRONMENT = ["PATH", "LANG", "LC_ALL", "SYSTEMROOT", "TEMP", "TMP"]

# Runs a script up to the point it parses its arguments, then writes the
# parser's description instead of parsing. The script is executed rather than
# imported because every script builds and parses its parser at module level.
PROBE_SOURCE = """
import json, runpy, sys
script_path, output_path = sys.argv[1], sys.argv[2]
import joybox.arguments as arguments
def describe(self, *args, **kwargs):
    with open(output_path, "w") as output_file:
        json.dump(self.describe(), output_file)
    raise SystemExit(0)
arguments.ArgumentParser.parse_args = describe
arguments.ArgumentParser.parse_known_args = describe
sys.argv = [script_path]
runpy.run_path(script_path, run_name = "joybox_describe")
"""

# Get the tool names in a scripts directory, with their paths
def find_scripts(scripts_dir):
    found = []
    for filename in sorted(os.listdir(scripts_dir)):
        if filename.endswith(".py") and not filename.startswith("_"):
            found.append((filename[:-3], os.path.join(scripts_dir, filename)))
    return found

# Describe a script's parser, run against a home directory holding only the
# default JoyBox.ini so nothing from the local one leaks into the documentation
def describe_script(script_path, shared_dir, timeout = 60):
    with tempfile.TemporaryDirectory() as home_dir:
        default_settings.create_default_config_file(os.path.join(home_dir, "JoyBox.ini"))
        output_path = os.path.join(home_dir, "parser.json")
        env = {name: os.environ[name] for name in PASSED_ENVIRONMENT if name in os.environ}
        env["HOME"] = home_dir
        env["USERPROFILE"] = home_dir
        env["PYTHONPATH"] = shared_dir
        result = subprocess.run(
            [sys.executable, "-c", PROBE_SOURCE, script_path, output_path],
            capture_output = True,
            text = True,
            timeout = timeout,
            cwd = home_dir,
            env = env)
        if not os.path.exists(output_path):
            raise RuntimeError("Unable to describe %s: %s" % (script_path, result.stderr.strip()[-2000:]))
        with open(output_path, "r") as output_file:
            spec = json.load(output_file)
    return replace_home_in_defaults(spec, home_dir)

# Swap the throwaway home directory for ~ in any default derived from it
def replace_home_in_defaults(spec, home_dir):
    def replace(value):
        if isinstance(value, str):
            return value.replace(home_dir, "~")
        if isinstance(value, list):
            return [replace(item) for item in value]
        return value
    for group in spec["groups"]:
        for option in group["options"]:
            option["default"] = replace(option["default"])
    return spec

