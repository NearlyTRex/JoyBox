# Get an option's flags as they were declared
def format_flags(option):
    if option["positional"]:
        return "<%s>" % option["dest"]
    return ", ".join(option["flags"])

# Get an option's placeholder value
def format_value(option):
    if option["positional"] or not option["takes_value"]:
        return ""
    if option["choices"]:
        return " <%s>" % "|".join(option["choices"]) if len(option["choices"]) <= 4 else " <%s>" % option["dest"]
    return " <%s>" % option["dest"]

# Get an option's cell in the options table
def format_option_cell(option):
    return ("`%s%s`" % (format_flags(option), format_value(option))).replace("|", "\\|")

# Get an option's description cell, with its default and allowed values
def format_description_cell(option):
    text = option["description"].strip().rstrip(".")
    parts = [text + "."]
    if option["required"] and not option["positional"]:
        parts.append("**Required.**")
    default = option["default"]
    if default not in (None, False, [], ""):
        if isinstance(default, list):
            default = ",".join(str(value) for value in default)
        parts.append("Default: `%s`." % default)
    if option["choices"]:
        parts.append("Allowed: %s." % ", ".join("`%s`" % choice for choice in option["choices"]))
    return " ".join(parts).replace("|", "\\|").replace("\n", " ")

# Get the synopsis line
def format_synopsis(tool_name, spec):
    words = [tool_name]
    for group in spec["groups"]:
        for option in group["options"]:
            if option["positional"]:
                words.append("<%s>" % option["dest"])
            elif option["required"]:
                words.append("%s%s" % (option["flags"][0], format_value(option)))
    words.append("[options]")
    return " ".join(words)

