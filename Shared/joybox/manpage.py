# Describe every script in a directory
def describe_scripts(scripts_dir, shared_dir):
    return {name: describe_script(path, shared_dir) for name, path in find_scripts(scripts_dir)}

# Get the pages that differ from what is on disk, and the files that would be removed
def find_stale_pages(pages, output_dir):
    stale = []
    for filename, content in pages.items():
        path = os.path.join(output_dir, filename)
        if not os.path.exists(path):
            stale.append(filename)
            continue
        with open(path, "r") as page_file:
            if page_file.read() != content:
                stale.append(filename)
    extra = []
    if os.path.isdir(output_dir):
        extra = sorted(name for name in os.listdir(output_dir) if name.endswith(".md") and name not in pages)
    return stale, extra

# Write every page, removing pages for tools that no longer exist
def write_pages(pages, output_dir):
    os.makedirs(output_dir, exist_ok = True)
    stale, extra = find_stale_pages(pages, output_dir)
    for filename in stale:
        with open(os.path.join(output_dir, filename), "w") as page_file:
            page_file.write(pages[filename])
    for filename in extra:
        os.remove(os.path.join(output_dir, filename))
    return stale, extra
