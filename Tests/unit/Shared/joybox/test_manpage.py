def test_the_throwaway_home_becomes_a_tilde():
    described = spec([option("path", default = "/tmp/abc/Locker"), option("list", default = ["/tmp/abc/x", 3])])

    manpage.replace_home_in_defaults(described, "/tmp/abc")

    assert [o["default"] for o in described["groups"][0]["options"]] == ["~/Locker", ["~/x", 3]]


