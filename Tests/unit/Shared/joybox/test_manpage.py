def test_a_described_script_does_not_see_the_callers_environment(tmp_path, shared_dir, monkeypatch):
    # A default read from the environment would put a token on a public page.
    monkeypatch.setenv("JOYBOX_TEST_SECRET", "hunter2")
    script = tmp_path / "tool.py"
    script.write_text(
        "import os\n"
        "import joybox.arguments as arguments\n"
        "parser = arguments.ArgumentParser(description = 'Tool')\n"
        "parser.add_string_argument(args = ('-k', '--key'), default = os.environ.get('JOYBOX_TEST_SECRET'), description = 'Key')\n"
        "args, unknown = parser.parse_known_args()\n")

    described = manpage.describe_script(str(script), shared_dir)

    assert described["groups"][0]["options"][0]["default"] is None
