# Imports
import os

# Third-party imports
import pytest

# Local imports
from joybox import manpage


###########################################################
# Helpers
###########################################################

def option(dest, flags = None, description = "Does a thing", **overrides):
    described = {
        "flags": flags if flags is not None else ["--%s" % dest],
        "dest": dest,
        "positional": False,
        "takes_value": True,
        "required": False,
        "description": description,
        "default": None,
        "choices": None,
    }
    described.update(overrides)
    return described


def spec(options = None, **overrides):
    described = {
        "description": "Do the thing.",
        "details": None,
        "examples": [["Run it", "tool --name x"]],
        "notes": [],
        "see_also": [],
        "section": "Things",
        "groups": [{"title": None, "options": options if options is not None else [option("name")]}],
    }
    described.update(overrides)
    return described


###########################################################
# Help problems
#
# These are what make the help text the documentation: a tool that fails any
# of them produces a page that leaves something out.
###########################################################

def test_complete_help_has_no_problems():
    assert manpage.find_help_problems("tool", spec(), ["tool"]) == []


@pytest.mark.parametrize("overrides,expected", [
    ({"description": " "}, "no description"),
    ({"section": None}, "no section"),
    ({"examples": []}, "no examples"),
    ({"examples": [["", "tool"]]}, "an example has no title"),
    ({"examples": [["Run it", "other --name x"]]}, "example does not run tool: other --name x"),
    ({"see_also": ["tool"]}, "see_also names itself"),
    ({"see_also": ["missing"]}, "see_also names an unknown tool: missing"),
])
def test_each_gap_is_reported(overrides, expected):
    assert expected in manpage.find_help_problems("tool", spec(**overrides), ["tool"])


def test_an_option_without_help_is_reported_by_its_flags():
    problems = manpage.find_help_problems("tool", spec([option("name", ["-n", "--name"], description = None)]), ["tool"])

    assert problems == ["no help text for -n, --name"]


