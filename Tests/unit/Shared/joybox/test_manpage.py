def test_only_changed_pages_are_written_and_orphans_removed(tmp_path):
    (tmp_path / "same.md").write_text("same")
    (tmp_path / "old.md").write_text("old")
    (tmp_path / "gone.md").write_text("gone")

    stale, extra = manpage.write_pages({"same.md": "same", "old.md": "new", "added.md": "added"}, str(tmp_path))

    assert (sorted(stale), extra) == (["added.md", "old.md"], ["gone.md"])
    assert sorted(os.listdir(tmp_path)) == ["added.md", "old.md", "same.md"]
    assert (tmp_path / "old.md").read_text() == "new"


def test_checking_writes_nothing(tmp_path):
    stale, extra = manpage.find_stale_pages({"new.md": "new"}, str(tmp_path))

    assert (stale, extra, os.listdir(tmp_path)) == (["new.md"], [], [])


