def test_the_synopsis_lists_required_options_and_positionals():
    options = [
        option("source", ["source"], positional = True, required = True),
        option("name", ["-n", "--name"], required = True),
        option("verbose", ["-v"], takes_value = False),
    ]

    assert manpage.format_synopsis("tool", spec(options)) == "tool <source> -n <name> [options]"


def test_a_short_choice_list_becomes_the_placeholder():
    assert manpage.format_value(option("mode", choices = ["Tree", "Local"])) == " <Tree|Local>"


def test_a_long_choice_list_keeps_the_name_as_placeholder():
    assert manpage.format_value(option("mode", choices = list("abcde"))) == " <mode>"


def test_pipes_are_escaped_inside_the_options_table():
    page = manpage.render_page("tool", spec([option("mode", ["-m"], choices = ["Tree", "Local"])]))

    assert "`-m <Tree\\|Local>`" in page
    assert "Allowed: `Tree`, `Local`." in page


def test_the_default_is_shown_only_when_there_is_one():
    page = manpage.render_page("tool", spec([option("name", default = "x"), option("other")]))

    assert "Default: `x`." in page
    assert page.count("Default:") == 1


def test_a_required_option_is_marked():
    page = manpage.render_page("tool", spec([option("name", required = True)]))

    assert "**Required.**" in page


def test_ungrouped_options_get_the_general_heading():
    assert "### General" in manpage.render_page("tool", spec())


def test_see_also_links_carry_the_other_tools_summary():
    page = manpage.render_page("tool", spec(see_also = ["other"]), {"other": "Do the other thing"})

    assert "- [other](other.md) — Do the other thing" in page


def test_the_page_says_it_is_generated():
    assert manpage.render_page("tool", spec()).startswith("<!-- Generated by build_man_pages from Scripts/bin/tool.py.")


def test_the_index_groups_tools_by_section():
    index = manpage.render_index({"b": spec(section = "Beta"), "a": spec(section = "Alpha"), "c": spec(section = None)})

    headings = [line for line in index.splitlines() if line.startswith("## ")]

    assert headings == ["## Alpha", "## Beta", "## Other"]


def test_render_all_adds_the_index():
    assert set(manpage.render_all({"tool": spec()})) == {"README.md", "tool.md"}


